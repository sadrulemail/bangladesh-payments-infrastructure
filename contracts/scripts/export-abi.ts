/**
 * Writes the contract ABIs to the SDK as typed constants, so the API and the console share one
 * definition of every function, event and error.
 *
 *   pnpm --filter @takarail/contracts export-abi
 */
import fs from "node:fs";
import path from "node:path";

import { artifacts } from "hardhat";

const CONTRACTS: Record<string, string> = {
  registry: "ParticipantRegistry",
  token: "TokenisedTaka",
  controller: "ReserveController",
  paymentSwitch: "PaymentSwitch",
  gateway: "RemittanceGateway",
  hub: "DisbursementHub",
};

async function main() {
  const lines = ["// Generated by contracts/scripts/export-abi.ts. Do not edit by hand.", "/* eslint-disable */", ""];
  for (const [key, name] of Object.entries(CONTRACTS)) {
    const { abi } = await artifacts.readArtifact(name);
    lines.push(`export const ${key}Abi = ${JSON.stringify(abi)} as const;`, "");
  }
  lines.push(
    "export const abis = {",
    ...Object.keys(CONTRACTS).map((key) => `  ${key}: ${key}Abi,`),
    "} as const;",
    "",
    "export type ContractName = keyof typeof abis;",
    "",
  );

  const target = path.resolve(__dirname, "../../packages/sdk/src/generated/abi.ts");
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, lines.join("\n"));
  console.log(`Wrote ${path.relative(process.cwd(), target)}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
